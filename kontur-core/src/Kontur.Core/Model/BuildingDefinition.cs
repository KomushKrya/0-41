namespace Kontur.Core.Model
{
	/// <summary>
	/// Дом на карте. Отвечает на вопрос «куда именно ткнуть метку», а не «что там происходит».
	///
	/// Зона и здание — разные слои, и путать их не стоит. Зона — механика: штриховка,
	/// вес в подборе вызовов, надбавка к требованиям. Здание — точка на плане города,
	/// одна из тех, что нарисованы геометрией карты. У вызова есть и то, и другое:
	/// зона говорит, насколько там паршиво, здание — в какой подъезд едет группа.
	/// </summary>
	public sealed class BuildingDefinition
	{
		public string Id { get; set; } = string.Empty;

		/// <summary>Сюда можно отправить группу. Ложь — дом есть на карте, но вызовов в нём не бывает.</summary>
		public bool IsDispatchTarget { get; set; }

		/// <summary>Главное управление. Отсюда группа выезжает и сюда возвращается.</summary>
		public bool IsHeadquarters { get; set; }

		/// <summary>
		/// Район, в котором стоит дом. Пусто — привязки нет, и планировщик считает
		/// дом подходящим для любой зоны. Это временное послабление: пока в карте
		/// не проставлены районы, иначе не выбралось бы ни одно здание.
		/// </summary>
		public string ZoneId { get; set; } = string.Empty;
	}
}
