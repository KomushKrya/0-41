namespace Kontur.Core.Model
{
	/// <summary>
	/// Тип диалога по радио. Не «правильность» в смысле успеха — успех считается
	/// сравнением характеристик, — а обещание цены: хороший вариант дешевле плохого.
	///
	/// Порядок значений значим: по нему конвертер проверяет, что тип и цена не разошлись,
	/// а ядро подставляет умолчания. Хуже типа — выше надбавка и риски.
	/// </summary>
	public enum MissionEventQuality
	{
		Good = 0,
		Neutral = 1,
		Bad = 2
	}
}
