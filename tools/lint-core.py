#!/usr/bin/env python3
"""
Структурные проверки C#-кода ядра без компилятора.

Зачем: полноценная сборка требует .NET SDK, который есть не везде и не всегда.
Этот скрипт ловит несколько классов ошибок, которые иначе всплывают только
на `dotnet build` — и каждый из них уже был допущен хотя бы раз.

Компилятор он не заменяет. Он сокращает круг: если здесь красное, собирать
бессмысленно; если зелёное — можно собирать.

Запуск из корня проекта:
    python tools/lint-core.py
"""

import os
import re
import sys
from collections import defaultdict

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКИ = ('kontur-core/src', 'scripts')


# ----------------------------------------------------------------- разбор

def вырезать_строки(текст, оставлять_дырки=True):
    """
    Убирает строковые литералы и комментарии, сохраняя переводы строк,
    чтобы номера строк не поехали.

    Содержимое интерполяционных дырок $"{...}" при оставлять_дырки=True
    сохраняется: это код, а не текст, и скобки в нём считаются.
    """
    вывод = []
    i = 0
    n = len(текст)

    while i < n:
        c = текст[i]

        # дословные строки: @"..." $@"..." @$"..."
        if текст.startswith('@"', i) or текст.startswith('$@"', i) or текст.startswith('@$"', i):
            i += 3 if текст[i] in '$@' and текст[i + 1] in '$@' else 2
            while i < n:
                if текст.startswith('""', i):
                    i += 2
                    continue
                if текст[i] == '"':
                    i += 1
                    break
                вывод.append('\n' if текст[i] == '\n' else ' ')
                i += 1
            continue

        # обычные и интерполированные строки
        if текст.startswith('$"', i) or c == '"':
            интерполяция = текст.startswith('$"', i)
            i += 2 if интерполяция else 1
            глубина = 0
            while i < n:
                ch = текст[i]
                if ch == '\\' and глубина == 0:
                    i += 2
                    continue
                if интерполяция and ch == '{':
                    if текст.startswith('{{', i):
                        i += 2
                        continue
                    глубина += 1
                    if оставлять_дырки:
                        вывод.append('{')
                    i += 1
                    continue
                if интерполяция and ch == '}':
                    if глубина > 0:
                        глубина -= 1
                        if оставлять_дырки:
                            вывод.append('}')
                    i += 1
                    continue
                if ch == '"' and глубина == 0:
                    i += 1
                    break
                if ch == '\n':
                    вывод.append('\n')
                elif глубина > 0 and оставлять_дырки:
                    вывод.append(ch)
                i += 1
            continue

        if c == "'":
            i += 1
            while i < n:
                if текст[i] == '\\':
                    i += 2
                    continue
                if текст[i] == "'":
                    i += 1
                    break
                i += 1
            continue

        if текст.startswith('//', i):
            j = текст.find('\n', i)
            i = n if j < 0 else j
            continue

        if текст.startswith('/*', i):
            j = текст.find('*/', i + 2)
            кусок = текст[i:n if j < 0 else j + 2]
            вывод.append('\n' * кусок.count('\n'))
            i = n if j < 0 else j + 2
            continue

        вывод.append(c)
        i += 1

    return ''.join(вывод)


def собрать_файлы():
    файлы = []
    for папка in ПАПКИ:
        путь = os.path.join(КОРЕНЬ, папка)
        for корень, _, имена in os.walk(путь):
            части = корень.split(os.sep)
            if 'obj' in части or 'bin' in части:
                continue
            for имя in имена:
                if имя.endswith('.cs'):
                    файлы.append(os.path.join(корень, имя))
    return sorted(файлы)


def коротко(путь):
    return os.path.relpath(путь, КОРЕНЬ).replace(os.sep, '/')


# ----------------------------------------------------------------- проверки

def проверить_скобки(файлы, беды):
    """Незакрытая скобка — самая частая поломка при правке большого метода."""
    for f in файлы:
        код = вырезать_строки(open(f, encoding='utf-8').read())
        for откр, закр, имя in (('{', '}', 'фигурные'), ('(', ')', 'круглые'), ('[', ']', 'квадратные')):
            if код.count(откр) != код.count(закр):
                беды.append(f"{коротко(f)}: не сходятся {имя} скобки "
                            f"({код.count(откр)} против {код.count(закр)})")


def проверить_экранирование(файлы, беды):
    """
    Обратный слэш внутри интерполяционной дырки $"{...}".

    Содержимое дырки разбирается как выражение, и \\" там недопустимо —
    кавычки внутри пишутся как есть. Ошибка выглядит безобидно и даёт
    десяток каскадных сообщений компилятора совсем в других строках.
    """
    for f in файлы:
        текст = open(f, encoding='utf-8').read()
        i = 0
        n = len(текст)
        строка = 1
        while i < n:
            if текст[i] == '\n':
                строка += 1
                i += 1
                continue
            if текст.startswith('$"', i) and not текст.startswith('$@"', i):
                i += 2
                глубина = 0
                while i < n:
                    c = текст[i]
                    if c == '\n':
                        строка += 1
                    if c == '\\' and глубина == 0:
                        i += 2
                        continue
                    if c == '{':
                        if текст.startswith('{{', i):
                            i += 2
                            continue
                        глубина += 1
                        i += 1
                        continue
                    if c == '}':
                        if глубина > 0:
                            глубина -= 1
                        i += 1
                        continue
                    if c == '\\' and глубина > 0:
                        беды.append(f"{коротко(f)}:{строка}: обратный слэш внутри "
                                    f"интерполяции — кавычки в {{...}} пишутся без экранирования")
                        i += 2
                        continue
                    if c == '"' and глубина == 0:
                        i += 1
                        break
                    i += 1
                continue
            i += 1


ОБЪЯВЛЕНИЕ_ТИПА = re.compile(
    r'\b(?:public|internal|private|protected)\s+'
    r'(?:sealed\s+|abstract\s+|static\s+|partial\s+|readonly\s+|ref\s+)*'
    r'(?:class|struct|interface|enum|record)\s+(\w+)')

ОБЪЯВЛЕНИЕ_ЧЛЕНА = re.compile(
    r'\b(?:public|internal|private|protected)\s+'
    r'(?:static\s+|readonly\s+|const\s+|virtual\s+|override\s+|sealed\s+|abstract\s+|async\s+)*'
    r'[\w\.<>,\?\[\]]+\s+(\w+)\s*(?:[\{;=\(])')


def собрать_члены_перечислений(код):
    """
    Имена значений enum. Нужны, чтобы MissionResolutionReason.CallMissed
    не выглядел как забытый using под сигнал CallMissed — имена совпадают,
    и такие совпадения в проекте не редкость.
    """
    имена = set()
    for m in re.finditer(r'\benum\s+\w+[^\{]*\{([^\}]*)\}', код, re.S):
        for кусок in m.group(1).split(','):
            кусок = кусок.split('=')[0].strip()
            if re.fullmatch(r'\w+', кусок):
                имена.add(кусок)
    return имена


def проверить_using(файлы, беды):
    """
    Тип используется, а его пространство имён не подключено.

    Строится индекс «имя типа -> пространства имён, где он объявлен», и для
    каждого файла смотрится, видно ли хоть одно. Отсеиваются три источника шума:
    члены самого файла (свойство GameOverReason), значения перечислений
    (MissionResolutionReason.CallMissed) и имена, объявленные ещё и в глобальном
    пространстве — как EventBus, которых в проекте два разных.
    """
    объявления = defaultdict(set)
    for f in файлы:
        код = вырезать_строки(open(f, encoding='utf-8').read())
        m = re.search(r'namespace\s+([\w\.]+)', код)
        пространство = m.group(1) if m else ''
        for m in ОБЪЯВЛЕНИЕ_ТИПА.finditer(код):
            объявления[m.group(1)].add(пространство)

    for f in файлы:
        код = вырезать_строки(open(f, encoding='utf-8').read())

        m = re.search(r'namespace\s+([\w\.]+)', код)
        своё = m.group(1) if m else None

        подключено = {''}
        подключено |= set(re.findall(r'using\s+(?:static\s+)?(?:\w+\s*=\s*)?([\w\.]+)\s*;', код))
        if своё:
            части = своё.split('.')
            for i in range(len(части)):
                подключено.add('.'.join(части[:i + 1]))

        здесь = {m.group(1) for m in ОБЪЯВЛЕНИЕ_ТИПА.finditer(код)}
        члены = {m.group(1) for m in ОБЪЯВЛЕНИЕ_ЧЛЕНА.finditer(код)}
        значения = собрать_члены_перечислений(код)

        for имя, пространства in объявления.items():
            if имя in здесь or имя in члены or имя in значения:
                continue
            if пространства & подключено:
                continue

            без_квалификации = код
            for пространство in пространства:
                if пространство:
                    без_квалификации = re.sub(
                        re.escape(пространство) + r'\.' + re.escape(имя), '', без_квалификации)

            if re.search(r'(?<![\w\.])' + re.escape(имя) + r'(?![\w])', без_квалификации):
                где = ', '.join(sorted(п for п in пространства if п))
                беды.append(f"{коротко(f)}: используется {имя}, но не подключено {где}")


def проверить_арность(файлы, беды):
    """
    Число аргументов при создании записи против её объявления.

    Сигналы и представления — позиционные записи, и добавленное поле ломает
    все места создания разом. Компилятор это, конечно, поймает, но здесь
    видно сразу все места, а не первое.
    """
    источники = ['kontur-core/src/Kontur.Core/Events/Signals.cs',
                 'kontur-core/src/Kontur.Core/Api/Views.cs']

    объявления = {}
    for отн in источники:
        путь = os.path.join(КОРЕНЬ, отн)
        if not os.path.exists(путь):
            continue
        текст = open(путь, encoding='utf-8').read()
        for m in re.finditer(r'record\s+(\w+)\s*\((.*?)\)\s*(?::\s*[\w\s,]+)?;', текст, re.S):
            параметры = вырезать_строки(m.group(2))
            глубина = 0
            счёт = 1 if параметры.strip() else 0
            for ch in параметры:
                if ch in '<([':
                    глубина += 1
                elif ch in '>)]':
                    глубина -= 1
                elif ch == ',' and глубина == 0:
                    счёт += 1
            объявления[m.group(1)] = счёт

    for f in файлы:
        код = вырезать_строки(open(f, encoding='utf-8').read())
        for имя, ожидается in объявления.items():
            for m in re.finditer(r'new\s+' + имя + r'\s*\(', код):
                i = m.end()
                глубина = 1
                счёт = 1
                непусто = False
                while i < len(код) and глубина > 0:
                    ch = код[i]
                    if ch in '<([':
                        глубина += 1
                    elif ch in '>)]':
                        глубина -= 1
                        if глубина == 0:
                            break
                    elif ch == ',' and глубина == 1:
                        счёт += 1
                    if not ch.isspace():
                        непусто = True
                    i += 1
                if not непусто:
                    счёт = 0
                if счёт != ожидается:
                    строка = код[:m.start()].count('\n') + 1
                    беды.append(f"{коротко(f)}:{строка}: {имя} ожидает {ожидается} "
                                f"аргументов, передано {счёт}")


def проверить_копии_контента(файлы, беды):
    """
    Вторая копия контента, разошедшаяся с игровой.

    В дереве живут две папки данных: data/ в корне (её читает игра) и
    kontur-core/content/ (автономный прогон ядра). Пока они совпадают, беды нет.
    Когда расходятся — харнесс считает баланс по одному контенту, а игра играет
    по другому, и обнаруживается это далеко не сразу.
    """
    основная = os.path.join(КОРЕНЬ, 'data')
    копия = os.path.join(КОРЕНЬ, 'kontur-core', 'content')

    if not os.path.isdir(основная) or not os.path.isdir(копия):
        return

    for имя in sorted(os.listdir(основная)):
        if not имя.endswith('.json'):
            continue

        путь_копии = os.path.join(копия, имя)
        if not os.path.exists(путь_копии):
            continue

        левый = open(os.path.join(основная, имя), encoding='utf-8').read()
        правый = open(путь_копии, encoding='utf-8').read()
        if левый != правый:
            беды.append(f"data/{имя} и kontur-core/content/{имя} разошлись — "
                        f"прогон ядра пойдёт не по тому контенту, что игра")


# ----------------------------------------------------------------- запуск

def main():
    файлы = собрать_файлы()
    if not файлы:
        print('Не найдено ни одного .cs — запускайте из корня проекта.')
        return 2

    проверки = (
        ('скобки', проверить_скобки),
        ('экранирование в интерполяции', проверить_экранирование),
        ('подключение пространств имён', проверить_using),
        ('арность записей', проверить_арность),
        ('копии контента', проверить_копии_контента),
    )

    всего = 0
    for имя, функция in проверки:
        беды = []
        функция(файлы, беды)
        значок = 'ок' if not беды else f'{len(беды)} шт.'
        print(f'{имя:32} {значок}')
        for беда in беды:
            print(f'    {беда}')
        всего += len(беды)

    print('-' * 60)
    print(f'файлов проверено: {len(файлы)}, находок: {всего}')
    return 1 if всего else 0


if __name__ == '__main__':
    sys.exit(main())
