#requires -version 5.1
<#
    Перевод ветки на историю KomushKrya/main.

    Зачем это нужно. Переезд на версию товарищей мы сделали руками: скачали архив
    и скопировали файлы поверх своих. Для git это выглядит как две независимо
    написанные версии одного и того же — отсюда 198 «конфликтов» в PR, хотя
    расхождений по существу почти нет.

    Что делает скрипт. Берёт дерево апстрима целиком, убирает файлы, которые
    товарищи удалили, а мы воскресили копированием, и накладывает сверху патч
    с нашими правками: слоты на вызове, снятие штриховки районов, записки
    сменщика, инструменты и документация.

    Патч (tools/our-changes.patch) заранее проверен на чистом дереве апстрима:
    ложится без единого отказа, линтер и сверка миссий проходят.

    Ничего не коммитит и не отправляет. git merge --abort вернёт всё назад.
#>

# Continue, а не Stop: git пишет в поток ошибок обычные сообщения о ходе работы,
# и при Stop PowerShell обрывает скрипт на успешной команде.
$ErrorActionPreference = 'Continue'

try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
    $OutputEncoding = [System.Text.Encoding]::UTF8
}
catch {
}

$корень = Split-Path -Parent $PSScriptRoot
Set-Location $корень

function Скажи {
    param([string]$Текст = '', [string]$Цвет = 'Gray')
    Write-Host $Текст -ForegroundColor $Цвет
}

function Шаг {
    param([string]$Текст)
    Скажи ''
    Скажи ('-' * 60) 'DarkGray'
    Скажи "  $Текст" 'Cyan'
    Скажи ('-' * 60) 'DarkGray'
}

<#
    Наши файлы, которых нет в апстриме и которые нужно сохранить.

    Записки сменщика товарищи потеряли при переезде — без них mission.py check
    ругается на все четыре дня. Файлы .uid принадлежат нашим новым экранам:
    в scripts/ они отслеживаются наравне с остальными.
#>
$оставить = @(
    'content/raw/ru/shift_notes/day_1.md',
    'content/raw/ru/shift_notes/day_2.md',
    'content/raw/ru/shift_notes/day_3.md',
    'content/raw/ru/shift_notes/day_4.md',
    'scripts/flow/GameFlow.cs.uid',
    'scripts/ui/CutscenePlayer.cs.uid',
    'scripts/ui/HiringScreen.cs.uid',
    'scripts/ui/MainMenu.cs.uid'
)

$патч = Join-Path $PSScriptRoot 'our-changes.patch'

Write-Host ''
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host '  Переход на историю KomushKrya/main' -ForegroundColor Cyan
Write-Host '============================================================' -ForegroundColor Cyan

# --- Проверки перед началом ----------------------------------
Шаг '0. Проверки'

if (-not (Test-Path (Join-Path $корень 'project.godot'))) {
    Скажи '[ОШИБКА] Запускать из корня проекта.' 'Red'
    return 1
}

if (-not (Test-Path $патч)) {
    Скажи "[ОШИБКА] Нет файла $патч" 'Red'
    return 1
}

& git rev-parse --verify --quiet upstream/main > $null 2>&1
if ($LASTEXITCODE -ne 0) {
    Скажи '[ОШИБКА] Не настроен upstream. Сначала:' 'Red'
    Скажи '    git remote add upstream https://github.com/KomushKrya/0-41.git'
    return 1
}

if (Test-Path (Join-Path $корень '.git\MERGE_HEAD')) {
    Скажи 'Найдено незавершённое слияние — отменяю его.' 'Yellow'
    & git merge --abort
}

# Проверяем только отслеживаемые файлы. Неотслеживаемые слияние не трогает,
# а их тут заведомо есть: сами инструменты этого перехода и .bat-обёртки.
& git diff --quiet HEAD
if ($LASTEXITCODE -ne 0) {
    Скажи ''
    Скажи '[ОШИБКА] Есть незакоммиченные правки в отслеживаемых файлах.' 'Red'
    Скажи 'Закоммитьте или откатите их: слияние их затрёт.' 'Red'
    Скажи ''
    & git status --short
    return 1
}

& git config core.quotepath false

$ветка = (& git rev-parse --abbrev-ref HEAD).Trim()
Скажи "Ветка: $ветка"
Скажи 'Рабочая папка чистая.' 'Green'

Скажи ''
Скажи 'Забираю свежий апстрим...'
& git fetch upstream

# --- Что лишнего у нас ---------------------------------------
Шаг '1. Файлы, которых у товарищей больше нет'

$наши = @(& git ls-tree -r --name-only HEAD)
$ихние = @(& git ls-tree -r --name-only upstream/main)
$ихниеНабор = [System.Collections.Generic.HashSet[string]]::new([string[]]$ихние)

$лишние = @()
foreach ($файл in $наши) {
    if (-not $ихниеНабор.Contains($файл) -and $оставить -notcontains $файл) {
        $лишние += $файл
    }
}

Скажи "Наших файлов: $($наши.Count), у них: $($ихние.Count)"
Скажи "Убрать: $($лишние.Count) (сохраняем $($оставить.Count) наших)"
Скажи ''

# Показываем не весь список — там полсотни текстур от старой модели компьютера.
$показать = $лишние | Where-Object { $_ -notlike '*PCNewFinal*' }
foreach ($файл in $показать) { Скажи "    $файл" 'DarkGray' }
$текстур = $лишние.Count - $показать.Count
if ($текстур -gt 0) { Скажи "    (и ещё $текстур файлов модели PCNewFinal)" 'DarkGray' }

Скажи ''
$ответ = Read-Host 'Продолжить? (д/н)'
if ($ответ -notmatch '^[дdyу]') {
    Скажи 'Отменено, ничего не тронуто.' 'Yellow'
    return 0
}

# --- Слияние -------------------------------------------------
Шаг '2. Подшиваю историю апстрима'

# Стратегия ours: дерево остаётся нашим, история их подшивается второй веткой
# предков. Конфликтов при этом не бывает вовсе — содержимое git не сравнивает.
# Дерево мы всё равно заменим следующим шагом.
& git merge --no-commit --no-ff -s ours upstream/main

if (-not (Test-Path (Join-Path $корень '.git\MERGE_HEAD'))) {
    Скажи '[ОШИБКА] Слияние не началось. Смотрите вывод git выше.' 'Red'
    return 1
}

Скажи 'История подшита.' 'Green'

# --- Убираем лишнее ------------------------------------------
Шаг '3. Убираю файлы, удалённые товарищами'

# Сначала с диска и из индекса, и только потом выкладываем их дерево. Порядок
# важен из-за переименований, отличающихся только регистром: docs/ЯДРО-API.md
# у них стал docs/ядро-api.md, а Windows считает это одним и тем же файлом.
foreach ($файл in $лишние) {
    & git rm -q -f --ignore-unmatch -- $файл > $null 2>&1
    if (Test-Path -LiteralPath $файл) {
        Remove-Item -LiteralPath $файл -Force -ErrorAction SilentlyContinue
    }
}

Скажи "Убрано файлов: $($лишние.Count)" 'Green'

# --- Их дерево -----------------------------------------------
Шаг '4. Выкладываю дерево апстрима'

& git checkout upstream/main -- .
if ($LASTEXITCODE -ne 0) {
    Скажи '[ОШИБКА] Не удалось выложить дерево апстрима.' 'Red'
    Скажи 'Отмените слияние: git merge --abort' 'Yellow'
    return 1
}

Скажи 'Дерево совпадает с KomushKrya/main.' 'Green'

# --- Наши правки ---------------------------------------------
Шаг '5. Накладываю наши правки'

& git apply --verbose $патч
if ($LASTEXITCODE -ne 0) {
    Скажи ''
    Скажи '[ОШИБКА] Патч не лёг.' 'Red'
    Скажи 'Такого быть не должно: он проверялся на этом же дереве апстрима.'
    Скажи 'Скорее всего, апстрим успел уйти вперёд с момента подготовки патча.'
    Скажи ''
    Скажи 'Отмените слияние: git merge --abort' 'Yellow'
    return 1
}

& git add -A

Скажи ''
Скажи 'Наложено: слоты на вызове, снятие штриховки районов,' 'Green'
Скажи 'записки сменщика, инструменты и документация.' 'Green'

# --- Сверка --------------------------------------------------
Шаг '6. Сверка'

$пропали = @()
foreach ($файл in $оставить) {
    if (-not (Test-Path -LiteralPath $файл)) { $пропали += $файл }
}

if ($пропали.Count -gt 0) {
    Скажи '[ВНИМАНИЕ] Пропали файлы, которые должны были остаться:' 'Red'
    foreach ($файл in $пропали) { Скажи "    $файл" 'Red' }
    Скажи 'Отмените слияние: git merge --abort' 'Yellow'
    return 1
}

Скажи 'Наши файлы на месте.' 'Green'

$изменено = @(& git diff --cached --name-only upstream/main)
Скажи "Отличий от KomushKrya/main: $($изменено.Count) файл(ов)" 'Cyan'
Скажи ''
foreach ($файл in $изменено) { Скажи "    $файл" 'DarkGray' }

Скажи ''
Скажи '============================================================' 'Cyan'
Скажи '  Слияние подготовлено, но НЕ закоммичено.' 'Cyan'
Скажи '============================================================' 'Cyan'
Скажи ''
Скажи 'Дальше:'
Скажи '  1. проверить.bat        собрать ядро и прогнать самопроверку'
Скажи '  2. git commit -F сообщение-коммита.txt'
Скажи '  3. git push'
Скажи ''
Скажи 'Передумать: git merge --abort' 'Yellow'
Скажи 'Коммитить только после зелёной сборки.' 'Yellow'

return 0
