#requires -version 5.1
<#
    Слияние с апстримом KomushKrya/0-41: наше дерево целиком плюс их проза и ассеты.

    Почему не обычное слияние с разбором конфликтов. Ядро у нас и у них — две
    независимо развивавшиеся версии одного кода: у них GameSession и RadioEncounter,
    у нас KonturSimulation, сохранения и модель Dispatch. Git видит это как один
    файл, переименованный и переписанный, и раскладывает конфликты по чужим путям.
    Разбор «этот файл наш, тот их» на таком материале промахивается: первая попытка
    потеряла семнадцать файлов, включая фасад ядра и мост в Godot.

    Поэтому здесь стратегия ours: дерево берётся наше целиком, история их —
    подшивается. Потерять что-либо невозможно по построению. А то, что нужно
    из апстрима, накладывается сверху явным списком путей.

    Ничего не коммитит. git merge --abort вернёт всё назад.
#>

# Continue, а не Stop, и это важно: git пишет в поток ошибок совершенно обычные
# сообщения — «Automatic merge went well; stopped before committing as requested».
# При Stop PowerShell считает такую строку исключением и обрывает скрипт на
# успешной команде. Об успехе здесь судим по коду возврата, а не по потокам.
$ErrorActionPreference = 'Continue'

try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
}
catch {
}

$корень = Split-Path -Parent $PSScriptRoot
Set-Location $корень

function Скажи {
    param([string]$Текст, [string]$Цвет = 'Gray')
    Write-Host $Текст -ForegroundColor $Цвет
}

<#
    Что берём из апстрима поверх нашего дерева.

    Только то, что не зависит от ядра: проза и художественные ассеты. Сцены и
    скрипты сюда не входят намеренно — они у них написаны под GameSession
    и с нашим фасадом не соберутся.
#>
$изАпстрима = @(
    'content/raw',
    'assets'
)

Write-Host ''
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host '  Слияние с апстримом: наше дерево + их проза и ассеты' -ForegroundColor Cyan
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host ''

# --- Проверки перед началом ---------------------------------
if (-not (Test-Path (Join-Path $корень 'project.godot'))) {
    Скажи '[ОШИБКА] Запускать из корня проекта.' 'Red'
    return 1
}

& git rev-parse --verify --quiet upstream/main > $null 2>&1
if ($LASTEXITCODE -ne 0) {
    Скажи '[ОШИБКА] Не вижу upstream/main. Сначала:' 'Red'
    Скажи '    git remote add upstream https://github.com/KomushKrya/0-41.git'
    Скажи '    git fetch upstream'
    return 1
}

if (Test-Path (Join-Path $корень '.git\MERGE_HEAD')) {
    Скажи 'Найдено незавершённое слияние — отменяю его.' 'Yellow'
    & git merge --abort
    Скажи ''
}

& git config core.quotepath false

$ветка = (& git rev-parse --abbrev-ref HEAD).Trim()
Скажи "Ветка: $ветка"

$грязно = (& git status --porcelain)
if ($грязно) {
    Скажи ''
    Скажи '[ОШИБКА] В рабочей папке есть несохранённые изменения.' 'Red'
    Скажи 'Закоммитьте их: слияние затрёт незакоммиченное.'
    return 1
}

# Запоминаем, что было до слияния, — потом сверим, что ничего не пропало.
$доСлияния = @(& git ls-tree -r --name-only HEAD)
Скажи "Файлов в ветке до слияния: $($доСлияния.Count)"

# --- Слияние стратегией ours --------------------------------
# Дерево остаётся нашим целиком, их история подшивается как вторая ветка предков.
# Конфликтов при этом не бывает вовсе: сравнивать содержимое git не пытается.
Скажи ''
Скажи 'Сливаю историю апстрима (дерево остаётся нашим)...'
& git merge --no-commit --no-ff -s ours upstream/main

if (-not (Test-Path (Join-Path $корень '.git\MERGE_HEAD'))) {
    Скажи '[ОШИБКА] Слияние не началось. Смотрите вывод git выше.' 'Red'
    return 1
}

# --- Накладываем их прозу и ассеты --------------------------
Скажи ''
foreach ($путь in $изАпстрима) {
    & git checkout upstream/main -- $путь
    if ($LASTEXITCODE -eq 0) {
        Скажи "Взято из апстрима: $путь" 'Cyan'
    }
    else {
        Скажи "В апстриме нет пути $путь — пропускаю" 'DarkGray'
    }
}

& git add -A

# --- Сверка: ничего не пропало ------------------------------
Скажи ''
$пропали = @()
foreach ($файл in $доСлияния) {
    if (-not (Test-Path -LiteralPath (Join-Path $корень $файл))) {
        $пропали += $файл
    }
}

if ($пропали.Count -gt 0) {
    Скажи "[ВНИМАНИЕ] Пропало файлов: $($пропали.Count)" 'Red'
    foreach ($файл in $пропали) {
        Скажи "    $файл" 'Red'
    }
    Скажи ''
    Скажи 'Так быть не должно. Отмените слияние: git merge --abort' 'Red'
    return 1
}

Скажи 'Сверка: ни один файл не пропал.' 'Green'

# --- Что изменилось -----------------------------------------
$изменено = @(& git diff --cached --name-only)
Скажи "Файлов взято из апстрима: $($изменено.Count)" 'Cyan'

Скажи ''
Скажи '============================================================' 'Cyan'
Скажи '  Слияние подготовлено, но НЕ закоммичено.' 'Cyan'
Скажи '============================================================' 'Cyan'
Скажи ''
Скажи 'Дальше:'
Скажи '  проверить.bat           собрать ядро и прогнать проверки'
Скажи '  git merge --abort       передумать и вернуть всё назад'
Скажи ''
Скажи 'Коммитить только после зелёной сборки.' 'Yellow'

return 0
