#requires -version 5.1
<#
    Сборка ядра К.О.Н.Т.У.Р. и самопроверка. Godot для этого не нужен.

    Запускается через проверить.bat в корне проекта. Почему PowerShell, а не .bat:
    cmd разбирает батник в кодировке консоли, и кириллица внутри команд рассыпается
    ещё до того, как отработает chcp. PowerShell читает скрипт как UTF-8 и не ломается.

    Весь вывод дублируется в проверка.log в корне проекта.
#>

$ErrorActionPreference = 'Stop'

# Чтобы вывод dotnet с кириллицей не превращался в кракозябры.
try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
    $OutputEncoding = [System.Text.Encoding]::UTF8
}
catch {
    # Не критично: сломается только оформление, но не сама сборка.
}

$корень = Split-Path -Parent $PSScriptRoot
$лог = Join-Path $корень 'проверка.log'

Set-Location $корень

"Сборка ядра К.О.Н.Т.У.Р." | Out-File -FilePath $лог -Encoding UTF8
"Дата: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')" | Out-File -FilePath $лог -Encoding UTF8 -Append

function Записать {
    param([string]$Текст, [string]$Цвет = 'Gray')
    Write-Host $Текст -ForegroundColor $Цвет
    $Текст | Out-File -FilePath $лог -Encoding UTF8 -Append
}

function Заголовок {
    param([string]$Текст)
    Записать ''
    Записать ('-' * 60) 'DarkGray'
    Записать "  $Текст" 'Cyan'
    Записать ('-' * 60) 'DarkGray'
}

<#
    Запускает команду, показывает вывод на экране и складывает его же в лог.
    Возвращает код возврата — по нему решаем, идти ли дальше.
#>
function Выполнить {
    param([string]$Файл, [string[]]$Аргументы)

    & $Файл @Аргументы 2>&1 | ForEach-Object {
        $строка = $_.ToString()
        Write-Host $строка
        $строка | Out-File -FilePath $лог -Encoding UTF8 -Append
    }

    return $LASTEXITCODE
}

Write-Host ''
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host '  Сборка ядра и самопроверка' -ForegroundColor Cyan
Write-Host '============================================================' -ForegroundColor Cyan

# --- Мы там, где думаем? -------------------------------------
if (-not (Test-Path (Join-Path $корень 'kontur-core\Kontur.Core.sln'))) {
    Записать '[ОШИБКА] Не вижу kontur-core\Kontur.Core.sln.' 'Red'
    Записать 'Скрипт должен лежать в tools/ внутри папки проекта.' 'Red'
    return 1
}

# --- .NET SDK на месте? --------------------------------------
$версия = $null
try {
    $версия = (& dotnet --version 2>$null | Select-Object -First 1)
}
catch {
    $версия = $null
}

if (-not $версия) {
    Записать ''
    Записать '[ОШИБКА] .NET SDK не найден.' 'Red'
    Записать ''
    Записать 'Скачайте .NET 8 SDK: https://dotnet.microsoft.com/download/dotnet/8.0'
    Записать 'Нужен именно SDK, а не Runtime: Runtime умеет только запускать,'
    Записать 'но не собирать.'
    Записать ''
    Записать 'После установки закройте это окно и откройте новое — иначе'
    Записать 'система не увидит изменившийся PATH.'
    return 1
}

Записать ''
Записать "Версия .NET SDK: $версия"

# --- Godot держит DLL заблокированной ------------------------
# Это уже случалось дважды: сборка «проходит», а в игре старое поведение.
$godot = Get-Process -Name 'Godot*' -ErrorAction SilentlyContinue
if ($godot) {
    Записать ''
    Записать '[ВНИМАНИЕ] Godot запущен.' 'Yellow'
    Записать ''
    Записать 'Пока открыто окно редактора или игры, файл Kontur.Core.dll'
    Записать 'заблокирован — сборка не сможет его перезаписать, и вы увидите'
    Записать 'старое поведение, решив, что правки не применились.'
    Записать ''
    Записать 'Закройте Godot и запустите скрипт заново.' 'Yellow'
    Записать ''
    Read-Host 'Enter — продолжить всё равно'
}

# --- 0. Структурные проверки ---------------------------------
# Дешёвый барьер перед сборкой: ловит скобки, забытые using и рассыпавшуюся
# арность записей. Не заменяет компилятор, но сообщения понятнее и сразу все.
$питон = $null
foreach ($кандидат in @('python', 'py', 'python3')) {
    try {
        & $кандидат --version *> $null
        if ($LASTEXITCODE -eq 0) { $питон = $кандидат; break }
    }
    catch {
    }
}

if ($питон) {
    Заголовок '0. Структурные проверки (без компилятора)'

    # Python на Windows пишет в кодировке консоли, а не UTF-8, и кириллица
    # в выводе превращается в кракозябры. Переменная лечит это на корню.
    $env:PYTHONIOENCODING = 'utf-8'
    Выполнить $питон @((Join-Path $PSScriptRoot 'lint-core.py')) | Out-Null
}

Set-Location (Join-Path $корень 'kontur-core')

# --- 1. Сборка -----------------------------------------------
Заголовок '1. Сборка (первый раз может занять минуту)'

$кодСборки = Выполнить 'dotnet' @('build', 'Kontur.Core.sln', '-c', 'Release', '--nologo')

if ($кодСборки -ne 0) {
    Записать ''
    Записать '============================================================' 'Red'
    Записать "  Сборка не прошла (код $кодСборки). Ошибки выше и в проверка.log" 'Red'
    Записать '============================================================' 'Red'
    Set-Location $корень
    return $кодСборки
}

# --- 2. Самопроверка -----------------------------------------
Заголовок '2. Самопроверка ядра'

$кодТестов = Выполнить 'dotnet' @(
    'run', '--project', 'src/Kontur.Harness', '-c', 'Release', '--no-build', '--', '--selftest')

# --- 3. Прогон четырёх смен ----------------------------------
Заголовок '3. Прогон четырёх смен подряд'

Выполнить 'dotnet' @(
    'run', '--project', 'src/Kontur.Harness', '-c', 'Release', '--no-build', '--',
    '--days', '4', '--seed', '41', '--strategy', 'best') | Out-Null

Set-Location $корень

Записать ''
Записать '============================================================' 'Cyan'
if ($кодТестов -eq 0) {
    Записать '  Сборка прошла, самопроверка зелёная.' 'Green'
}
else {
    Записать '  Собралось, но самопроверка нашла провалы — смотрите выше.' 'Yellow'
}
Записать "  Полный вывод: $лог" 'Cyan'
Записать '============================================================' 'Cyan'

return 0
