#requires -version 5.1
<#
    Отправка рабочей папки в GitHub.

    Первый запуск: спросит адрес репозитория и ветку, превратит папку проекта
    в клон и запомнит настройки навсегда. Дальше — только описание правок.

    Ничего не отправляется, пока не показан список файлов и вы его не подтвердили.

    Запускается через запушить.bat в корне проекта.
#>

$ErrorActionPreference = 'Stop'

try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
}
catch {
}

$корень = Split-Path -Parent $PSScriptRoot
Set-Location $корень

function Скажи {
    param([string]$Текст, [string]$Цвет = 'Gray')
    Write-Host $Текст -ForegroundColor $Цвет
}

Write-Host ''
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host '  К.О.Н.Т.У.Р. — отправка в репозиторий' -ForegroundColor Cyan
Write-Host "  Папка: $корень" -ForegroundColor DarkGray
Write-Host '============================================================' -ForegroundColor Cyan
Write-Host ''

# --- 1. Мы там, где думаем? ----------------------------------
if (-not (Test-Path (Join-Path $корень 'project.godot'))) {
    Скажи '[ОШИБКА] В этой папке нет project.godot.' 'Red'
    Скажи 'Скрипт должен лежать в tools/ внутри папки проекта.' 'Red'
    return 1
}

# --- 2. Git установлен? --------------------------------------
$версияGit = $null
try {
    $версияGit = (& git --version 2>$null | Select-Object -First 1)
}
catch {
    $версияGit = $null
}

if (-not $версияGit) {
    Скажи '[ОШИБКА] Git не найден.' 'Red'
    Скажи 'Установите с https://git-scm.com/download/win и запустите скрипт заново.'
    return 1
}

$естьРепозиторий = Test-Path (Join-Path $корень '.git')

# --- 2a. Представиться, если git видит нас впервые -----------
# Без этого коммит просто откажется создаваться, причём сообщение git выдаёт длинное
# и пугающее. Спросить два поля один раз проще, чем разбирать его потом.
if ($true) {
    $имя = (& git config user.name 2>$null)
    $почта = (& git config user.email 2>$null)

    if (-not $имя -or -not $почта) {
        Скажи 'Git ещё не знает, кто вы. Это спрашивается один раз.' 'Cyan'
        Скажи ''

        if (-not $имя) {
            $имя = Read-Host 'Ваше имя'
            if ($имя) { & git config --global user.name $имя }
        }

        if (-not $почта) {
            Скажи 'Почта должна совпадать с привязанной к GitHub, иначе коммиты' 'DarkGray'
            Скажи 'не свяжутся с вашим профилем.' 'DarkGray'
            $почта = Read-Host 'Почта'
            if ($почта) { & git config --global user.email $почта }
        }

        Скажи ''
    }
}

# --- 3. Ловушка: репозиторий выше по дереву ------------------
# Если git init когда-то сделали в C:\Users\<имя>, то отсюда git увидит ЕГО,
# и add -A утащит в коммит .ssh, AppData и .claude.json.
if (-not $естьРепозиторий) {
    $чужой = (& git rev-parse --show-toplevel 2>$null)
    if ($LASTEXITCODE -eq 0 -and $чужой) {
        Скажи '[ОПАСНО] Здесь нет своего репозитория, но выше по дереву найден чужой:' 'Red'
        Скажи "    $чужой" 'Red'
        Скажи ''
        Скажи 'Коммит отсюда затянет в него посторонние файлы — вплоть до ключей SSH'
        Скажи 'и настроек. Скрипт остановлен.'
        Скажи ''
        Скажи 'Что сделать: удалить лишний репозиторий командой'
        Скажи "    rmdir /s /q `"$чужой\.git`"" 'Yellow'
        Скажи 'и запустить скрипт заново.'
        return 1
    }
}

# --- 4. Первый запуск: создаём клон --------------------------
if (-not $естьРепозиторий) {
    Скажи 'Репозиторий здесь ещё не заведён. Настроим один раз.' 'Cyan'
    Скажи ''
    Скажи 'Адрес репозитория — со страницы GitHub, кнопка Code.'
    Скажи 'Например: https://github.com/имя/название.git' 'DarkGray'
    Скажи ''

    $адрес = Read-Host 'Адрес репозитория'
    if (-not $адрес) {
        Скажи 'Адрес не введён, отмена.' 'Yellow'
        return 1
    }

    $ветка = Read-Host 'Ветка [core-sim]'
    if (-not $ветка) { $ветка = 'core-sim' }

    Скажи ''
    Скажи 'Создаю репозиторий...'
    & git init -b $ветка
    if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

    & git remote add origin $адрес
    if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

    Скажи 'Забираю историю с сервера...'
    & git fetch origin
    if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

    & git rev-parse --verify --quiet "origin/$ветка" > $null 2>&1
    if ($LASTEXITCODE -eq 0) {
        # Ветка на сервере есть. reset --mixed подкладывает её историю под наши
        # файлы: файлы на диске не трогаются, но push перестаёт считать историю
        # чужой. Без этого получились бы две независимые истории.
        Скажи "Ветка $ветка на сервере есть, подключаюсь к её истории..."
        & git reset --mixed "origin/$ветка"
        if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

        & git branch --set-upstream-to="origin/$ветка" $ветка > $null 2>&1
    }
    else {
        Скажи "Ветки $ветка на сервере нет — будет создана при отправке."
    }

    Скажи ''
}
else {
    $ветка = (& git rev-parse --abbrev-ref HEAD).Trim()

    # Репозиторий есть, а адреса нет — так бывает, если прошлый запуск оборвали
    # между git init и вводом адреса. Без этой ветки скрипт доходил бы до push
    # и падал там с невнятной ошибкой про отсутствующий origin.
    $адресOrigin = (& git remote get-url origin 2>$null)
    if (-not $адресOrigin) {
        Скажи 'Репозиторий заведён, но адрес сервера не задан.' 'Yellow'
        Скажи 'Адрес — со страницы GitHub, кнопка Code.' 'DarkGray'
        Скажи ''

        $адрес = Read-Host 'Адрес репозитория'
        if (-not $адрес) {
            Скажи 'Адрес не введён, отмена.' 'Yellow'
            return 1
        }

        & git remote add origin $адрес
        if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

        Скажи 'Забираю историю с сервера...'
        & git fetch origin
        if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

        & git rev-parse --verify --quiet "origin/$ветка" > $null 2>&1
        if ($LASTEXITCODE -eq 0) {
            Скажи "Ветка $ветка на сервере есть, подключаюсь к её истории..."
            & git reset --mixed "origin/$ветка"
            if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

            & git branch --set-upstream-to="origin/$ветка" $ветка > $null 2>&1
        }
        else {
            Скажи "Ветки $ветка на сервере нет — будет создана при отправке."
        }

        Скажи ''
    }
}

Скажи "Ветка: $ветка" 'Cyan'
Скажи ''

# --- 5. Показываем, что уйдёт в коммит -----------------------
Скажи ('-' * 60) 'DarkGray'
Скажи '  Что изменилось:' 'Cyan'
Скажи ('-' * 60) 'DarkGray'

& git add -A
& git status --short

Скажи ('-' * 60) 'DarkGray'
Скажи ''

& git diff --cached --quiet
if ($LASTEXITCODE -eq 0) {
    Скажи 'Изменений нет — отправлять нечего.' 'Yellow'
    return 0
}

Скажи 'Проверьте список выше. Здесь должны быть только файлы проекта.'
Скажи 'Если видите .ssh, AppData, .claude.json или что-то из домашней'
Скажи 'папки — закройте окно, ничего не отправлено.' 'Yellow'
Скажи ''

$ответ = Read-Host 'Продолжить? (д/н)'
if ($ответ -notmatch '^[дdyу]') {
    Скажи 'Отменено. Изменения остались подготовленными, коммита нет.' 'Yellow'
    return 0
}

# --- 6. Коммит -----------------------------------------------
Скажи ''
$описание = Read-Host 'Описание правок [промежуточное сохранение]'
if (-not $описание) { $описание = 'промежуточное сохранение' }

& git commit -m $описание
if ($LASTEXITCODE -ne 0) { return $LASTEXITCODE }

# --- 7. Отправка ---------------------------------------------
Скажи ''
Скажи 'Отправляю на сервер...'
& git push -u origin $ветка

if ($LASTEXITCODE -ne 0) {
    Скажи ''
    Скажи '[ОШИБКА] Отправить не удалось.' 'Red'
    Скажи 'Коммит при этом сохранён локально — ничего не потеряно.'
    Скажи ''
    Скажи 'Частые причины:'
    Скажи '  * не пройдена авторизация — GitHub попросит вход в отдельном окне;'
    Скажи '  * на сервере есть правки, которых нет здесь — сделайте git pull --rebase;'
    Скажи '  * нет прав на запись в эту ветку.'
    return $LASTEXITCODE
}

Скажи ''
Скажи '============================================================' 'Green'
Скажи "  Готово. Ветка $ветка обновлена." 'Green'
Скажи '============================================================' 'Green'

return 0
