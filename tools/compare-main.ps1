#requires -version 5.1
<#
    Что нового в KomushKrya/main и с чем именно оно конфликтует.

    Ничего не меняет: только забирает свежие ветки с сервера и складывает
    отчёт в сверка-с-main.txt. Ни коммитов, ни слияний, ни правок файлов.

    Нужен потому, что GitHub сообщает о конфликтах списком имён, а по именам
    нельзя понять, что делать: «data/missions.json конфликтует» одинаково
    выглядит и когда товарищи добавили миссию, и когда они переписали ту же
    строку, что и мы. Отчёт показывает обе стороны.

    Запускается через сверить-с-main.bat в корне проекта.
#>

# Continue, а не Stop: git пишет в поток ошибок обычные сообщения о ходе
# работы, и при Stop PowerShell обрывает скрипт на успешной команде.
$ErrorActionPreference = 'Continue'

try {
    [Console]::OutputEncoding = [System.Text.Encoding]::UTF8
    $OutputEncoding = [System.Text.Encoding]::UTF8
}
catch {
}

$корень = Split-Path -Parent $PSScriptRoot
$отчёт = Join-Path $корень 'сверка-с-main.txt'

Set-Location $корень

function Записать {
    param([string]$Текст = '')
    Write-Host $Текст
    $Текст | Out-File -FilePath $отчёт -Encoding UTF8 -Append
}

if (Test-Path $отчёт) { Remove-Item $отчёт -Force }

if (-not (Test-Path (Join-Path $корень 'project.godot'))) {
    Write-Host '[ОШИБКА] Запускать из корня проекта.' -ForegroundColor Red
    return 1
}

& git rev-parse --verify --quiet upstream/main > $null 2>&1
if ($LASTEXITCODE -ne 0) {
    Write-Host '[ОШИБКА] Не настроен upstream. Сначала:' -ForegroundColor Red
    Write-Host '    git remote add upstream https://github.com/KomushKrya/0-41.git'
    return 1
}

& git config core.quotepath false

Write-Host ''
Write-Host 'Забираю свежие ветки с сервера...' -ForegroundColor Cyan
& git fetch upstream
& git fetch origin

$ветка = (& git rev-parse --abbrev-ref HEAD).Trim()
$база = (& git merge-base HEAD upstream/main).Trim()
$верх = (& git rev-parse upstream/main).Trim()

Записать '============================================================'
Записать "  Сверка $ветка с KomushKrya/main"
Записать "  $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
Записать '============================================================'
Записать ''
Записать "наша ветка:      $ветка ($((& git rev-parse --short HEAD).Trim()))"
Записать "upstream/main:   $($верх.Substring(0,7))"
Записать "общий предок:    $($база.Substring(0,7))"
Записать ''

if ($база -eq $верх) {
    Записать 'Наша ветка уже содержит весь upstream/main — конфликтов быть не должно.'
    Записать 'Если GitHub всё равно ругается, обновите страницу PR.'
    return 0
}

# --- Что нового у них ----------------------------------------------
Записать '------------------------------------------------------------'
Записать '  1. Коммиты, которых у нас нет'
Записать '------------------------------------------------------------'
& git log --oneline --no-decorate "$база..upstream/main" 2>&1 | ForEach-Object { Записать "  $_" }
Записать ''

Записать '------------------------------------------------------------'
Записать '  2. Файлы, которые они трогали'
Записать '------------------------------------------------------------'
& git diff --stat "$база..upstream/main" 2>&1 | ForEach-Object { Записать "  $_" }
Записать ''

# --- Пересечение: тронуто с обеих сторон ---------------------------
$ихФайлы = @(& git diff --name-only "$база..upstream/main")
$нашиФайлы = @(& git diff --name-only "$база..HEAD")
$общие = @($ихФайлы | Where-Object { $нашиФайлы -contains $_ })

Записать '------------------------------------------------------------'
Записать "  3. Тронуто и ими, и нами: $($общие.Count) файл(ов)"
Записать '------------------------------------------------------------'
Записать '  Только эти и могут конфликтовать. Остальное сольётся само.'
Записать ''
foreach ($файл in $общие) { Записать "  $файл" }
Записать ''

# --- Их правки в спорных файлах ------------------------------------
Записать '------------------------------------------------------------'
Записать '  4. Что именно они изменили в спорных файлах'
Записать '------------------------------------------------------------'
foreach ($файл in $общие) {
    Записать ''
    Записать "===== $файл"
    & git diff "$база..upstream/main" -- $файл 2>&1 | ForEach-Object { Записать $_ }
}

Записать ''
Записать '============================================================'
Записать "  Отчёт: $отчёт"
Записать '============================================================'

return 0
